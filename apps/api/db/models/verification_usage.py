"""Private, privacy-minimized usage event records (not billing records)."""

from __future__ import annotations

from datetime import datetime

from sqlalchemy import CheckConstraint, DateTime, Float, Index, SmallInteger, String, func
from sqlalchemy.orm import Mapped, mapped_column

from apps.api.db.base import Base


class VerificationUsageEvent(Base):
    __tablename__ = "verification_usage_events"
    __table_args__ = (
        CheckConstraint("status_code BETWEEN 100 AND 599", name="status_code_range"),
        CheckConstraint("latency_ms >= 0", name="latency_nonnegative"),
        Index("ix_verification_usage_actor_time", "actor_fingerprint", "occurred_at"),
        Index("ix_verification_usage_occurred_at", "occurred_at"),
    )

    # Generated by audit middleware, not supplied by the caller.
    request_id: Mapped[str] = mapped_column(String(24), primary_key=True)
    # HMAC pseudonym, NOT the user's email or OAuth subject.
    actor_fingerprint: Mapped[str] = mapped_column(String(24), nullable=False)
    occurred_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False
    )
    status_code: Mapped[int] = mapped_column(SmallInteger, nullable=False)
    outcome: Mapped[str] = mapped_column(String(32), nullable=False)
    latency_ms: Mapped[float] = mapped_column(Float, nullable=False)
